# Verify empirical tails against full OLS refits, independently of the
# projection shortcut used by the package. Reuse exactly the same weights.
set.seed(311)
weights <- matrix(sample(c(-1, 1), nrow(Y) * 29L, replace = TRUE), nrow(Y), 29L)
fit <- lfpm_fit(Y, F)
X <- cbind(1, F)
reference_L <- vapply(seq_len(ncol(weights)), function(b) {
  refit <- lm.fit(X, fit$U * weights[, b])
  variance <- colSums(refit$residuals^2) / (nrow(Y) - ncol(X))
  squared <- refit$coefficients[1L, ]^2 * fit$q / variance
  cumsum(sort(squared, decreasing = TRUE))[c(5L, 20L)]
}, numeric(2L))
reference_L <- t(reference_L)
observed <- cumsum(sort(fit$alpha^2 * fit$q / fit$s2, decreasing = TRUE))[c(5L, 20L)]
empirical_p <- (1 + colSums(sweep(reference_L, 2L, observed, ">="))) / 30
emp <- adal_test(Y, F, B = 29L, calibration = "empirical", multipliers = weights)
close_to(emp$components$statistic, observed)
close_to(emp$components$p.value, empirical_p)
close_to(emp$components$bootstrap.mean, colMeans(reference_L))
stopifnot(identical(emp$endpoint_epsilon, 1 / (40 + 32)))
clipped <- pmin(pmax(empirical_p, emp$endpoint_epsilon), 1 - emp$endpoint_epsilon)
close_to(emp$statistic, mean(tan(pi * (.5 - clipped))))
close_to(emp$p.value, pcauchy(unname(emp$statistic), lower.tail = FALSE))
stopifnot(emp$variance_audit$legacy_variance_safeguard_count == 0)
# Deliberately small units exercise the historical empirical variance floor.
scaled_emp <- adal_test(Y * 1e-12, F, B = 29L, calibration = "empirical", multipliers = weights)
stopifnot(scaled_emp$variance_audit$variance_floor == 1e-20,
          scaled_emp$variance_audit$legacy_variance_safeguard_count == 29L * 40L,
          scaled_emp$variance_audit$minimum_unclipped_refitted_variance < 1e-20)
scaled_fit <- lfpm_fit(Y * 1e-12, F)
scaled_reference <- t(vapply(seq_len(ncol(weights)), function(b) {
  refit <- lm.fit(X, scaled_fit$U * weights[, b])
  variance <- pmax(colSums(refit$residuals^2) / (nrow(Y) - ncol(X)), 1e-20)
  squared <- refit$coefficients[1L, ]^2 * scaled_fit$q / variance
  cumsum(sort(squared, decreasing = TRUE))[c(5L, 20L)]
}, numeric(2L)))
close_to(scaled_emp$components$bootstrap.mean, colMeans(scaled_reference))
fixed <- l_test(Y, F, k = 5L, B = 29L, multipliers = weights)
close_to(fixed$bootstrap.statistics, reference_L[, 1L])
close_to(fixed$p.value, empirical_p[1L])

# A one-asset, intercept-only L-test must not inherit the AdaL N>=40 limit.
