small <- l_test(small_Y, empty_F, k = 1L, B = 29L, multipliers = weights)
stopifnot(inherits(small, "htest"), is.finite(small$p.value),
          length(small$bootstrap.statistics) == 29L)
small_fit <- lm.fit(matrix(1, nrow(Y), 1L), small_Y)
small_ref <- vapply(seq_len(ncol(weights)), function(b) {
  z <- lm.fit(matrix(1, nrow(Y), 1L), small_fit$residuals * weights[, b])
  as.numeric(z$coefficients)^2 * nrow(Y) /
    (sum(z$residuals^2) / (nrow(Y) - 1L))
}, numeric(1L))
close_to(small$bootstrap.statistics, small_ref)

